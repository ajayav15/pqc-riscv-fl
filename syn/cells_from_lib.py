"""
cells_from_lib.py : zero-delay Verilog functional models of the NanGate45 cells
(generated from the liberty 'function' / 'ff' attributes) for gate-level
simulation of the synthesized netlists with Verilator or iverilog.
Usage: python3 syn/cells_from_lib.py <netlist.v>... > syn/out/nangate_cells.v
"""
import re
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import netlist as NL  # noqa: E402


def to_verilog(expr):
    toks = re.findall(r"[A-Za-z_][A-Za-z0-9_]*|[!&|^()+*']|[01]", expr)
    pos = [0]

    def peek():
        return toks[pos[0]] if pos[0] < len(toks) else None

    def take():
        t = toks[pos[0]]; pos[0] += 1; return t

    def p_or():
        x = p_xor()
        while peek() in ('|', '+'):
            take(); x = '(%s | %s)' % (x, p_xor())
        return x

    def p_xor():
        x = p_and()
        while peek() == '^':
            take(); x = '(%s ^ %s)' % (x, p_and())
        return x

    def p_and():
        x = p_un()
        while peek() is not None and (peek() in ('&', '*', '(', '!') or re.match(r'[A-Za-z_01]', peek())):
            if peek() in ('&', '*'):
                take()
            x = '(%s & %s)' % (x, p_un())
        return x

    def p_un():
        t = take()
        if t == '!':
            x = '(~%s)' % p_un()
        elif t == '(':
            x = p_or(); take()
        elif t in ('0', '1'):
            x = "1'b" + t
        else:
            x = t
        while peek() == "'":
            take(); x = '(~%s)' % x
        return x
    return p_or()


def main():
    lib = os.environ.get('NANGATE_LIB', '/home/claude/tools/pdk/orfs/flow/platforms/nangate45/lib/'
                         'NangateOpenCellLibrary_typical.lib')
    cells, _ = NL.load_liberty(lib)
    used = set()
    for f in sys.argv[1:]:
        used |= set(re.findall(r'^\s*([A-Z][A-Z0-9]*_X\d+)\s', open(f).read(), flags=re.M))
    print('// generated by cells_from_lib.py from %s' % os.path.basename(lib))
    print('`timescale 1ns/1ps')
    for name in sorted(used):
        c = cells[name]
        ins = [p for p, pp in c.pins.items() if pp['dir'] == 'input']
        outs = [p for p, pp in c.pins.items() if pp['dir'] == 'output']
        ports = ', '.join(['input ' + p for p in ins] + ['output ' + p for p in outs])
        print('module %s(%s);' % (name, ports))
        if c.ff is not None:
            if set(c.ff) - {'iq', 'iqn', 'next_state', 'clocked_on'}:
                raise SystemExit('unsupported flop ' + name)
            print('  reg IQ = 1\'b0;')
            print('  always @(posedge %s) IQ <= %s;' % (c.ff['clocked_on'], to_verilog(c.ff['next_state'])))
            for o in outs:
                f = c.pins[o]['func']
                print('  assign %s = %s;' % (o, 'IQ' if f == c.ff['iq'] else '~IQ'))
        else:
            for o in outs:
                print('  assign %s = %s;' % (o, to_verilog(c.pins[o]['func'])))
        print('endmodule')


if __name__ == '__main__':
    main()
