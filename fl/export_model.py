"""
export_model.py : int8 deployment of the federated detector on the RV32 node.

  * trains the FedAvg detector on the gate-level ML-KEM window streams
  * converts benign calibration (mu, sd) to sensor-LSB units, quantizes
    weights/activations (int8, per-tensor) and writes sw/fw/det_model.h,
    plus the Q15 FFT twiddles and a test vector set (det_vectors.h)
  * int_forward() is a bit-exact Python model of the C integer MLP
Usage: python3 fl/export_model.py
"""
import os
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import scenarios as S   # noqa: E402
import fedlearn as F    # noqa: E402
import datasets as D    # noqa: E402

ROOT = os.path.join(HERE, '..')
FW = os.path.join(ROOT, 'sw', 'fw')
ADC = 256.0                     # sensor LSB per unit (normalized) trace std
LINEAR = {0, 1, 2, 3, 4} | set(range(17, 33))   # features that scale with sensor units
N_VEC = 48
IN_SCALE = 16          # int8 input = normalized feature * 16 (range +-8 sd)


COLS = None            # feature subset (None: all 38); set by --variant
SUFFIX = ''


def train(seed=0):
    import run_fl as R
    src = D.KEMSource()
    nodes = R.build(src, seed)
    if COLS is not None:
        nodes = [dict(n, X=n['X'][:, COLS], Xt=n['Xt'][:, COLS]) for n in nodes]
    nin = nodes[0]['X'].shape[1]
    g, _ = F.fedavg([(n['X'], n['y']) for n in nodes], nin, rounds=R.ROUNDS, seed=seed)
    return src, nodes, g


def calib(src, seed=0):
    """benign calibration of node 0 in raw (un-normalized) feature units"""
    rng = np.random.default_rng(100 + seed)
    env = S.node_environment(rng, 0)
    atk = list(rng.choice(S.ATTACKS, 2, replace=False))
    X, y, kd, ev, tpl = D.stream(src, rng, env, atk, 2000)
    return env, tpl, X[y == 0].mean(0), X[y == 0].std(0) + 1e-6


def quantize(g, Xcal):
    p = g.p
    s_in = 1 / IN_SCALE
    sW = {k: np.abs(p[k]).max() / 127 for k in ('W1', 'W2', 'W3')}
    qW = {k: np.round(p[k] / sW[k]).astype(int) for k in sW}
    a1 = np.maximum(Xcal @ p['W1'] + p['b1'], 0)
    s_h1 = np.quantile(a1, 0.999) / 127 + 1e-9
    a2 = np.maximum(a1 @ p['W2'] + p['b2'], 0)
    s_h2 = np.quantile(a2, 0.999) / 127 + 1e-9
    q = dict(qW=qW,
             b1=np.round(p['b1'] / (s_in * sW['W1'])).astype(int),
             b2=np.round(p['b2'] / (s_h1 * sW['W2'])).astype(int),
             b3=int(np.round(p['b3'][0] / (s_h2 * sW['W3']))),
             m1=int(round(s_in * sW['W1'] / s_h1 * 65536)),
             m2=int(round(s_h1 * sW['W2'] / s_h2 * 65536)),
             s3=s_h2 * sW['W3'])
    return q


def int_forward(q, qin):
    """bit-exact model of the C MLP (qin: int8 inputs, shape (n, nin))"""
    a1 = qin @ q['qW']['W1'] + q['b1']
    h1 = np.clip((a1.astype(np.int64) * q['m1']) >> 16, 0, 127)
    a2 = h1 @ q['qW']['W2'] + q['b2']
    h2 = np.clip((a2.astype(np.int64) * q['m2']) >> 16, 0, 127)
    return h2 @ q['qW']['W3'][:, 0] + q['b3']


def carr(name, a, ctype='int32_t'):
    a = np.asarray(a)
    if a.ndim == 1:
        return 'static const %s %s[%d] = {%s};\n' % (ctype, name, len(a), ','.join(str(int(v)) for v in a))
    rows = ',\n  '.join('{%s}' % ','.join(str(int(v)) for v in r) for r in a)
    return 'static const %s %s[%d][%d] = {\n  %s};\n' % (ctype, name, a.shape[0], a.shape[1], rows)


def main():
    src, nodes, g = train()
    env, tpl, mu, sd = calib(src)
    cols = list(range(len(mu))) if COLS is None else list(COLS)
    mu, sd = mu[cols], sd[cols]
    # the deployed model sees features normalized with node 0's benign calibration
    n0 = nodes[0]
    q = quantize(g, n0['X'])
    qin = np.clip(np.floor(n0['Xt'] * IN_SCALE), -127, 127).astype(int)
    li = int_forward(q, qin)
    pf = g.predict(n0['Xt'])
    agree = float(((li > 0) == (pf >= 0.5)).mean())
    print('int8 MLP vs float model decision agreement on node-0 test: %.4f' % agree)
    # device units: linear features scale by ADC; Q12 fixed point
    mu_dev = np.array([m * (ADC if c in LINEAR else 1.0) for c, m in zip(cols, mu)])
    sd_dev = np.array([s * (ADC if c in LINEAR else 1.0) for c, s in zip(cols, sd)])
    nin = len(mu)
    h = ['/* generated by fl/export_model.py */\n#pragma once\n#include <stdint.h>\n',
         '#define DET_NIN %d\n#define DET_H1 %d\n#define DET_H2 %d\n' % (nin, q['qW']['W1'].shape[1], q['qW']['W2'].shape[1]),
         '#define DET_HAS_SEL 1\n', carr('det_sel', cols, 'uint8_t'),
         carr('det_mu', np.round(mu_dev * 4096), 'int64_t'),
         carr('det_isd', np.round(4096 / sd_dev), 'int64_t'),
         carr('det_tpl', np.round(tpl * ADC), 'int16_t'),
         carr('det_W1', q['qW']['W1'], 'int8_t'), carr('det_b1', q['b1']),
         carr('det_W2', q['qW']['W2'], 'int8_t'), carr('det_b2', q['b2']),
         carr('det_W3', q['qW']['W3'][:, 0], 'int8_t'),
         'static const int32_t det_b3 = %d;\nstatic const int32_t det_m1 = %d;\nstatic const int32_t det_m2 = %d;\n'
         % (q['b3'], q['m1'], q['m2'])]
    open(os.path.join(FW, 'det_model%s.h' % SUFFIX), 'w').write(''.join(h))
    k = np.arange(64)
    open(os.path.join(FW, 'det_twiddle_cos.h'), 'w').write(','.join(str(int(round(32767 * np.cos(2 * np.pi * i / 128)))) for i in k))
    open(os.path.join(FW, 'det_twiddle_sin.h'), 'w').write(','.join(str(int(round(32767 * np.sin(2 * np.pi * i / 128)))) for i in k))
    # test vectors: a node-0 window stream (raw traces) with Python reference decisions
    rng = np.random.default_rng(5)
    xs, ys, ref = [], [], []
    prev = src.benign(rng)
    hist = []
    state_kinds = ['BEN'] * 16 + ['CC'] * 8 + ['BEN'] * 8 + ['REP'] * 8 + ['BEN'] * 8
    rep = src.benign(rng)
    feats = []
    for kd in state_kinds:
        base = src.chosen(rng, None) if kd == 'CC' else (rep.copy() if kd == 'REP' else src.benign(rng))
        x = S.apply_benign(rng, base, env)
        r = D.residual(x, tpl)
        f = np.concatenate([S.features(x, prev, tpl), D.history_features(r, hist), [np.log1p(env['rate']), 0.0]])
        hist = (hist + [r])[-D.H_WIN:]
        feats.append(f); xs.append(np.clip(np.round(x * ADC), -32768, 32767)); ys.append(int(kd != 'BEN'))
        prev = x
    Fz = (np.array(feats)[:, cols] - mu) / sd
    ref = int_forward(q, np.clip(np.floor(Fz * IN_SCALE), -127, 127).astype(int))
    v = ['/* generated by fl/export_model.py: node-0 window stream + reference */\n#pragma once\n',
         '#define DET_NVEC %d\n' % len(xs), carr('det_x', np.array(xs), 'int16_t'),
         carr('det_ref', ref), carr('det_lbl', ys, 'uint8_t'),
         'static const int32_t det_lograte_q12 = %d;\n' % int(round(np.log1p(env['rate']) * 4096))]
    open(os.path.join(FW, 'det_vectors%s.h' % SUFFIX), 'w').write(''.join(v))
    np.savez(os.path.join(ROOT, 'results', 'det_export%s.npz' % SUFFIX), ref=ref, y=ys, feats=np.array(feats),
             agree=agree, s3=q['s3'])
    print('wrote det_model.h / det_vectors.h; python int8 decisions on vectors:', (ref > 0).astype(int).tolist())


if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == '--variant':
        sys.path.insert(0, os.path.join(ROOT, 'analysis'))
        import det_lite
        COLS = det_lite.VARIANTS[sys.argv[2]]
        SUFFIX = '_' + sys.argv[2]
    main()
